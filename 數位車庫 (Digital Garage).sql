-- 車輛表 (Vehicles)
CREATE TABLE "Vehicles" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "user_id" uuid NOT NULL REFERENCES auth.users("id") ON DELETE CASCADE,
  "brand" varchar NOT NULL,
  "model" varchar NOT NULL,
  "vehicle_type" varchar NOT NULL CHECK ("vehicle_type" IN ('car', 'motorcycle', 'other')),
  "year" integer,
  "manufacture_date" date CHECK ("manufacture_date" IS NULL OR "manufacture_date" <= CURRENT_DATE),
  "registration_date" date CHECK ("registration_date" IS NULL OR "registration_date" <= CURRENT_DATE),
  "purchase_date" date,
  "purchase_price" decimal(12,2) CHECK ("purchase_price" IS NULL OR "purchase_price" >= 0),
  "fuel_type" fuel_type,
  "engine_displacement_cc" integer CHECK ("engine_displacement_cc" IS NULL OR "engine_displacement_cc" > 0),
  "license_plate" varchar,
  "initial_mileage" integer NOT NULL DEFAULT 0 CHECK ("initial_mileage" >= 0),
  "current_mileage" integer NOT NULL DEFAULT 0 CHECK ("current_mileage" >= 0),
  "created_at" timestamptz NOT NULL DEFAULT now(),
  "updated_at" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT chk_vehicles_mileage_consistency CHECK ("current_mileage" >= "initial_mileage")
);

-- 車輛照片 (VehiclePhotos)
CREATE TABLE "VehiclePhotos" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "vehicle_id" integer NOT NULL REFERENCES "Vehicles"("id") ON DELETE CASCADE,
  "url" varchar NOT NULL,
  "sort_order" integer NOT NULL DEFAULT 0,
  "is_cover" boolean NOT NULL DEFAULT false,
  "created_at" timestamptz NOT NULL DEFAULT now()
);

-- 加油紀錄 (Refuels)
CREATE TABLE "Refuels" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "vehicle_id" integer NOT NULL REFERENCES "Vehicles"("id") ON DELETE CASCADE,
  "refuel_date" date NOT NULL,
  "mileage" integer NOT NULL CHECK ("mileage" >= 0),
  "volume" decimal(10,2) NOT NULL CHECK ("volume" > 0),
  "price_per_unit" decimal(10,2),
  "total_cost" decimal(10,2) NOT NULL CHECK ("total_cost" >= 0),
  "fuel_type" fuel_type NOT NULL,
  "created_at" timestamptz NOT NULL DEFAULT now(),
  "updated_at" timestamptz NOT NULL DEFAULT now()
);

-- 保養與維修紀錄 (MaintenanceRecords)
CREATE TABLE "MaintenanceRecords" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "vehicle_id" integer NOT NULL REFERENCES "Vehicles"("id") ON DELETE CASCADE,
  "record_type" maintenance_record_type NOT NULL,
  "item_name" varchar NOT NULL,
  "service_date" date NOT NULL,
  "mileage" integer NOT NULL CHECK ("mileage" >= 0),
  "cost" decimal(10,2) NOT NULL DEFAULT 0 CHECK ("cost" >= 0),
  "shop_name" varchar,
  "note" text,
  "created_at" timestamptz NOT NULL DEFAULT now(),
  "updated_at" timestamptz NOT NULL DEFAULT now()
);

-- 保養維修照片 (MaintenancePhotos)
CREATE TABLE "MaintenancePhotos" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "maintenance_record_id" integer NOT NULL REFERENCES "MaintenanceRecords"("id") ON DELETE CASCADE,
  "url" varchar NOT NULL,
  "sort_order" integer NOT NULL DEFAULT 0,
  "created_at" timestamptz NOT NULL DEFAULT now()
);

-- 保養提醒 (Reminders)
CREATE TABLE "Reminders" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "vehicle_id" integer NOT NULL REFERENCES "Vehicles"("id") ON DELETE CASCADE,
  "item_name" varchar NOT NULL,
  "interval_km" integer,
  "interval_months" integer,
  "base_mileage" integer,
  "base_date" date,
  "last_completed_mileage" integer,
  "last_completed_date" date,
  "last_maintenance_record_id" integer REFERENCES "MaintenanceRecords"("id") ON DELETE SET NULL,
  "status" reminder_status NOT NULL DEFAULT 'active',
  "created_at" timestamptz NOT NULL DEFAULT now(),
  "updated_at" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT chk_interval_not_both_null CHECK (
    "interval_km" IS NOT NULL OR "interval_months" IS NOT NULL
  )
);

-- 改裝品 (Modifications)
CREATE TABLE "Modifications" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "vehicle_id" integer NOT NULL REFERENCES "Vehicles"("id") ON DELETE CASCADE,
  "item_name" varchar NOT NULL,
  "category" modification_category NOT NULL,
  "brand" varchar,
  "model" varchar,
  "purchase_price" decimal(10,2) CHECK ("purchase_price" IS NULL OR "purchase_price" >= 0),
  "install_price" decimal(10,2) CHECK ("install_price" IS NULL OR "install_price" >= 0),
  "purchase_date" date,
  "install_date" date,
  "install_mileage" integer CHECK ("install_mileage" IS NULL OR "install_mileage" >= 0),
  "shop_name" varchar,
  "note" text,
  "created_at" timestamptz NOT NULL DEFAULT now(),
  "updated_at" timestamptz NOT NULL DEFAULT now()
);

-- 改裝照片 (ModificationPhotos)
CREATE TABLE "ModificationPhotos" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "modification_id" integer NOT NULL REFERENCES "Modifications"("id") ON DELETE CASCADE,
  "url" varchar NOT NULL,
  "sort_order" integer NOT NULL DEFAULT 0,
  "photo_type" varchar,
  "created_at" timestamptz NOT NULL DEFAULT now()
);

-- 改裝調校版本組 (ModificationSettingSets)
CREATE TABLE "ModificationSettingSets" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "modification_id" integer NOT NULL REFERENCES "Modifications"("id") ON DELETE CASCADE,
  "name" varchar NOT NULL,
  "recorded_date" date NOT NULL DEFAULT CURRENT_DATE,
  "mileage" integer CHECK ("mileage" IS NULL OR "mileage" >= 0),
  "is_current" boolean NOT NULL DEFAULT false,
  "note" text,
  "created_at" timestamptz NOT NULL DEFAULT now(),
  "updated_at" timestamptz NOT NULL DEFAULT now()
);

-- 改裝參數細項 (ModificationSettings)
CREATE TABLE "ModificationSettings" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "setting_set_id" integer NOT NULL REFERENCES "ModificationSettingSets"("id") ON DELETE CASCADE,
  "setting_name" varchar NOT NULL,
  "setting_value" varchar NOT NULL,
  "unit" varchar,
  "created_at" timestamptz NOT NULL DEFAULT now(),
  "updated_at" timestamptz NOT NULL DEFAULT now()
);

-- 週期性規費與到期管理 (RecurringExpenses - P2-2)
CREATE TABLE "RecurringExpenses" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "vehicle_id" integer NOT NULL REFERENCES "Vehicles"("id") ON DELETE CASCADE,
  "category" recurring_expense_category NOT NULL,
  "title" varchar(100) NOT NULL,
  "amount" decimal(12,2) NOT NULL DEFAULT 0 CHECK ("amount" >= 0),
  "paid_date" date NOT NULL,
  "coverage_start_date" date NOT NULL,
  "coverage_end_date" date NOT NULL,
  "notes" text,
  "created_at" timestamptz NOT NULL DEFAULT now(),
  "updated_at" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT chk_recurring_coverage_order CHECK ("coverage_end_date" >= "coverage_start_date")
);


