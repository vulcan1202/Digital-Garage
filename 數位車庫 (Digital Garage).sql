-- ==========================================
-- 6. 車輛動態時間軸 View (Timeline)
-- 包含 security_invoker 保證繼承 RLS，並做好 NULL 日期與金額容錯
-- 包含 5 大生命週期事件：加油、保養維修、改裝、購車入庫、週期規費
-- ==========================================
CREATE VIEW vehicle_timeline 
WITH (security_invoker = true) 
AS
  -- 1. 加油事件
  SELECT 
    vehicle_id, 
    'refuel' AS event_type, 
    id AS event_id, 
    refuel_date AS event_date, 
    mileage, 
    COALESCE(total_cost, 0) AS cost,
    fuel_type::text AS title,
    NULL::text AS description,
    created_at
  FROM "Refuels"

  UNION ALL

  -- 2. 維修/保養事件
  SELECT 
    vehicle_id, 
    record_type::text AS event_type, 
    id AS event_id, 
    service_date AS event_date, 
    mileage, 
    COALESCE(cost, 0) AS cost,
    item_name AS title,
    note AS description,
    created_at
  FROM "MaintenanceRecords"

  UNION ALL

  -- 3. 改裝事件 (優先安裝日，無安裝日降級為購買日，最後降級為建立建檔日)
  SELECT 
    vehicle_id, 
    'modification' AS event_type, 
    id AS event_id, 
    COALESCE(install_date, purchase_date, created_at::date) AS event_date, 
    install_mileage AS mileage, 
    (COALESCE(purchase_price, 0) + COALESCE(install_price, 0)) AS cost,
    item_name AS title,
    note AS description,
    created_at
  FROM "Modifications"

  UNION ALL

  -- 4. 車輛購入入庫事件 (僅當 purchase_date IS NOT NULL 時產生，禁止使用 created_at 假造)
  SELECT 
    id AS vehicle_id,
    'purchase' AS event_type,
    id AS event_id,
    purchase_date AS event_date,
    initial_mileage AS mileage,
    COALESCE(purchase_price, 0) AS cost,
    (brand || ' ' || model || ' 購入入庫') AS title,
    ('入庫基準里程: ' || initial_mileage || ' KM') AS description,
    created_at
  FROM "Vehicles"
  WHERE purchase_date IS NOT NULL

  UNION ALL

  -- 5. 週期規費事件 (牌照稅、公路養管費、定期檢驗、保險)
  -- 顯式指定 NULL::integer AS mileage 與 COALESCE(amount, 0) AS cost 確保 UNION 型別一致性
  SELECT 
    vehicle_id, 
    'recurring_expense' AS event_type, 
    id AS event_id, 
    paid_date AS event_date, 
    NULL::integer AS mileage, 
    COALESCE(amount, 0) AS cost,
    title,
    notes AS description,
    created_at
  FROM "RecurringExpenses";


