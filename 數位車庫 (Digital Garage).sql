-- 週期性規費類別 (燃料稅正名為公路使用養護安全管理費，簡稱公路養管費)
CREATE TYPE "recurring_expense_category" AS ENUM (
  'license_tax',           -- 牌照稅 (每年4月開徵)
  'road_maintenance_fee',  -- 公路使用養護安全管理費 (簡稱公路養管費，原燃料使用費，每年7月開徵)
