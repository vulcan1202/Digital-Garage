-- ==========================================
-- 4. 自動更新 updated_at 觸發器 (Triggers)
-- ==========================================
CREATE OR REPLACE FUNCTION update_timestamp_column()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER update_vehicles_updated_at BEFORE UPDATE ON "Vehicles" FOR EACH ROW EXECUTE FUNCTION update_timestamp_column();
CREATE TRIGGER update_refuels_updated_at BEFORE UPDATE ON "Refuels" FOR EACH ROW EXECUTE FUNCTION update_timestamp_column();
CREATE TRIGGER update_maintenance_updated_at BEFORE UPDATE ON "MaintenanceRecords" FOR EACH ROW EXECUTE FUNCTION update_timestamp_column();
CREATE TRIGGER update_reminders_updated_at BEFORE UPDATE ON "Reminders" FOR EACH ROW EXECUTE FUNCTION update_timestamp_column();
CREATE TRIGGER update_modifications_updated_at BEFORE UPDATE ON "Modifications" FOR EACH ROW EXECUTE FUNCTION update_timestamp_column();
CREATE TRIGGER update_mod_settingsets_updated_at BEFORE UPDATE ON "ModificationSettingSets" FOR EACH ROW EXECUTE FUNCTION update_timestamp_column();
CREATE TRIGGER update_mod_settings_updated_at BEFORE UPDATE ON "ModificationSettings" FOR EACH ROW EXECUTE FUNCTION update_timestamp_column();
CREATE TRIGGER update_recurring_expenses_updated_at BEFORE UPDATE ON "RecurringExpenses" FOR EACH ROW EXECUTE FUNCTION update_timestamp_column();


